use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    generate_rock_abi_consts();
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("espidf") {
        embuild::espidf::sysenv::output();
    }
}

/// Single source of truth for cross-language constants (audit phase 5, A3):
/// `#define ROCK_ABI_*` from main/rock_protocol_abi.h and the enum order of
/// `rock_ui_event_type_t` from main/gui/rock_gui.h are emitted here as Rust
/// `pub const`s into OUT_DIR. esp-idf-sys bindgen does not export
/// project-internal headers, so this is the deliberate binding path.
///
/// Event numbers come from the *enum order* (not hand-copied #defines) so
/// inserting or removing an enumerator in rock_gui.h renumbers the Rust side
/// automatically on the next build.
fn generate_rock_abi_consts() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let mut rs = String::from(
        "// @generated by build.rs from main/rock_protocol_abi.h and main/gui/rock_gui.h.\n\
         // Do not edit; change the headers and rebuild.\n",
    );

    let abi = fs::read_to_string(manifest.join("main/rock_protocol_abi.h"))
        .expect("read main/rock_protocol_abi.h");
    for line in abi.lines() {
        let line = line.trim_start();
        let Some(rest) = line.strip_prefix("#define") else {
            continue;
        };
        let mut it = rest.split_whitespace();
        if let (Some(name), Some(value)) = (it.next(), it.next()) {
            if name.starts_with("ROCK_ABI_") {
                let digits: String =
                    value.chars().take_while(|c| c.is_ascii_digit()).collect();
                writeln!(rs, "pub const {name}: u64 = {digits};").unwrap();
            }
        }
    }

    let gui = fs::read_to_string(manifest.join("main/gui/rock_gui.h"))
        .expect("read main/gui/rock_gui.h");
    let enum_body = extract_enum_block(&gui).expect("rock_ui_event_type_t enum in rock_gui.h");
    let mut value: u64 = 0;
    for line in enum_body.lines() {
        let line = line.split("//").next().unwrap_or("");
        for ident in line.split(',') {
            // "ROCK_UI_EVT_NONE = 0" -> identifier before any '=' / whitespace
            let ident = ident.split('=').next().unwrap_or("").trim();
            if ident.chars().next().is_some_and(|c| c.is_ascii_uppercase())
                && ident.chars().all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_')
            {
                writeln!(rs, "pub const {ident}: u64 = {value};").unwrap();
                value += 1;
            }
        }
    }
    assert!(value >= 12, "unexpectedly few rock_ui_event_type_t entries");

    fs::write(out_dir.join("rock_abi_consts.rs"), rs).unwrap();
    println!("cargo:rerun-if-changed=main/rock_protocol_abi.h");
    println!("cargo:rerun-if-changed=main/gui/rock_gui.h");
}

/// Body of the `typedef enum { ... } rock_ui_event_type_t` block in
/// rock_gui.h (brace-matched, comments still attached).
fn extract_enum_block(source: &str) -> Option<String> {
    let start = source.find("rock_ui_event_type_t")?; // typedef name after the block
    let open = source[..start].rfind('{')?;
    let mut depth = 0usize;
    for (i, b) in source.as_bytes().iter().enumerate().skip(open) {
        match b {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    return Some(source[open + 1..i].to_string());
                }
            }
            _ => {}
        }
    }
    None
}
